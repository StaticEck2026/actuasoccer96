"""Generate godot/scripts/core/consts.gd (class GlobConsts): every constant the
match engine uses.  Sources, in increasing priority:
  1. simple numeric #defines of the surviving headers (DATA.H, 3DENG.H, DEFINES.H ...)
  2. enum constants from the Watcom debug info of the original objects (AUDIO.H enums ...)
  3. values recovered from the original object code (tools/recovered/consts_part*.json)
"""
import os, re, sys, json, glob
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from omf import OMF
from wdbg import Types
SRC = os.path.join(HERE, '..', 'SOURCE')
OUT = os.path.join(HERE, '..', 'godot', 'scripts', 'core', 'consts.gd')
PRAT = 'PRAT_'

consts = {}   # name -> (gd_expr, comment, origin)

def set_c(n, expr, comment, origin):
    consts[n] = (expr, comment, origin)

# 1. headers
HEADERS = ['DATA.H', '3DENG.H', 'DEFINES.H', 'EURODEFS.H', 'EURO_DEF.H', 'ANDYDEFS.H', 'DATA.EQU']
num = r'[-+]?(?:\d+\.\d*|\.\d+|\d+)(?:[eE][-+]?\d+)?[fFlL]?|0x[0-9a-fA-F]+'
for h in HEADERS:
    t = open(os.path.join(SRC, h), 'rb').read().decode('latin1').replace('\r', '')
    t = re.sub(r'/\*.*?\*/', '', t, flags=re.S)
    t = re.sub(r'//.*', '', t)
    for m in re.finditer(r'^\s*#define\s+([A-Za-z_]\w*)\s+([^\n]*?)\s*$', t, flags=re.M):
        n, v = m.group(1), m.group(2).strip()
        if not v: continue
        e = v
        if not re.fullmatch(r'[\s\d\.\+\-\*/\(\)xXa-fA-F]+', e): continue
        e = re.sub(r'(\d)\.(?!\d)', r'\1.0', e)   # 29./69 -> 29.0/69
        e = re.sub(r'(?<![\w.])\.(\d)', r'0.\1', e)
        e = re.sub(r'(\d+\.?\d*)[fFlL]\b', r'\1', e)
        if re.search(r'[a-wyzA-WYZ]', e.replace('0x', '')): continue
        if n not in consts:
            set_c(n, e, h, 'header')

# 2. enums from debug info
for f in sorted(glob.glob(os.path.join(SRC, '*.OBJ'))):
    try:
        o = OMF(f)
    except Exception:
        continue
    segs = [k for k, s in enumerate(o.segdefs) if s and s[0] == '$$TYPES']
    if not segs: continue
    try:
        T = Types(bytes(o.segdata[segs[0]]))
    except Exception:
        continue
    for t in T.t.values():
        if t['k'] == 'enum':
            for n, v in t['consts']:
                if re.fullmatch(r'[A-Z_][A-Z0-9_]*', n) and (n not in consts or consts[n][2] == 'header'):
                    set_c(n, str(v), 'enum (' + os.path.basename(f) + ')', 'enum')

# 3. recovered
for p in sorted(glob.glob(os.path.join(HERE, 'recovered', 'consts_*.json'))):
    d = json.load(open(p))
    for n, v in d.items():
        ty = v.get('type'); val = v.get('value')
        ev = (v.get('evidence') or '').replace('\n', ' ')[:150]
        if ty == 'skip':
            if isinstance(val, (int, float)) and not isinstance(val, bool) and n.startswith('_G'):
                set_c(n, str(val), 'skip/' + ev, 'recovered')
            continue
        if ty == 'flag':
            set_c(n, 'true' if val else 'false', '#ifdef flag. ' + ev, 'recovered')
            continue
        expr = v.get('expr')
        if expr and 'prat' in expr:
            e = expr.replace('prat', PRAT)
            e = re.sub(r'(\d)\.(?!\d)', r'\1.0', e)
            set_c(n, e, v.get('confidence', '') + ' ' + ev, 'recovered')
            continue
        if val is None:
            set_c(n, '0', 'UNRESOLVED ' + ev, 'recovered')
            continue
        if ty == 'float' or isinstance(val, float):
            s = repr(float(val))
        else:
            s = str(int(val))
        set_c(n, s, v.get('confidence', '') + ' ' + ev, 'recovered')

# overrides verified against the object code
set_c('PI', '3.1415926536', 'verified: MATHS.OBJ CONST double 3.1415926536 (DEFINES.H has a stale 3.1415)', 'verified')
for n in ('TRUE', 'FALSE'):
    consts.pop(n, None)   # defined in CBase

# placeholders for constants still pending
pend = os.path.join(HERE, 'all_consts.txt')
skipped = set()
for p in glob.glob(os.path.join(HERE, 'recovered', 'consts_*.json')):
    skipped |= {n for n, v in json.load(open(p)).items() if v.get('type') == 'skip'}
for n in open(pend).read().split():
    if n not in consts and n not in skipped and re.fullmatch(r'[A-Z_][A-Z0-9_]*', n):
        set_c(n, '0', 'PENDING recovery', 'pending')

order = sorted(consts)
lines = ['# AUTO-GENERATED by tools/gen_consts.py. Do not edit by hand.',
         '# Constants of the original match engine. "recovered" values were read back from',
         '# the compiled original object code (the defining headers are missing from the source).',
         'class_name GlobConsts extends CBase', '',
         '# prat: pitch units per yard (glob_var.h float prat = 10.666667, never modified).',
         'const %s := 10.666667' % PRAT, '']
# emit header constants first (other exprs may reference? they don't), then others
for n in order:
    e, c, o = consts[n]
    lines.append('const %s = %s  # [%s] %s' % (n, e, o, c.replace('\n', ' ')))
open(OUT, 'w').write('\n'.join(lines) + '\n')
print('wrote', len(order), 'constants;', sum(1 for v in consts.values() if v[2] == 'pending'), 'pending')
